"""Refresh Codex adapters from the local Claude agent definitions.

Run from the repository root with api/.venv/Scripts/python.exe .codex/sync-agents.py.
The source bodies remain shared, so ordinary instruction edits need no regeneration.
"""

import json
from pathlib import Path
import tomllib

import yaml


ROOT = Path(__file__).resolve().parents[1]
DESTINATION = ROOT / ".codex" / "agents"


def main():
    DESTINATION.mkdir(exist_ok=True)
    for source in sorted((ROOT / ".claude" / "agents").glob("*.md")):
        _, frontmatter, _ = source.read_text(encoding="utf-8").split("---", 2)
        metadata = yaml.safe_load(frontmatter)
        name = metadata["name"]
        assert name == source.stem, source
        skills = metadata.get("skills", [])
        for skill in skills:
            assert (ROOT / ".agents" / "skills" / skill / "SKILL.md").is_file(), skill
        instructions = (
            "Read AGENTS.md and .claude/agents-roster.md from the repository root. "
            f"Then read {source.relative_to(ROOT).as_posix()} and follow its Markdown body "
            "as this role's instructions. Resolve its links relative to that source file. "
            "Its YAML model and tools fields configure Claude only; use the model in this "
            "Codex adapter and inherit session effort, permissions and available tools. "
            "Use Codex file, search and shell "
            "tools for the equivalent operations. Read SKILL.md files directly; do not "
            "assume a Claude Skill tool or plugin is installed. "
            "User authorization already given in the session remains valid; do not ask "
            "for the same permission again. Follow the roster's Codex runtime notes."
        )
        if skills:
            instructions += " Before starting, read these project skills: " + ", ".join(
                f".agents/skills/{skill}/SKILL.md" for skill in skills
            ) + "."
        content = "# Generated by .codex/sync-agents.py; edit the shared Markdown source.\n"
        for key, value in {
            "name": name,
            "description": metadata["description"],
            "model": "gpt-6-astra" if metadata.get("model") == "opus" else "gpt-6-sol",
            "developer_instructions": instructions,
        }.items():
            content += f"{key} = {json.dumps(value, ensure_ascii=False)}\n"
        tomllib.loads(content)
        target = DESTINATION / f"{name}.toml"
        if target.exists() and not target.read_text(encoding="utf-8").startswith(
            "# Generated by .codex/sync-agents.py;"
        ):
            raise RuntimeError(f"Refusing to overwrite a manually maintained agent: {target}")
        target.write_text(content, encoding="utf-8")
        print(name)


if __name__ == "__main__":
    main()
