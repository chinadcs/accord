"""Generate Accord's Codex adapters and skill discovery entries from Claude sources.

Run ``python .codex/sync-agents.py`` from the repository root, or add ``--check``
for a read-only drift check. Requires Python 3.10+ and PyYAML. Product code is not
required. Generated files never replace manual files or delete obsolete entries.
"""

import argparse
import json
from pathlib import Path
import re
import sys

import yaml


ROOT = Path(__file__).resolve().parents[1]
ADAPTER_MARKER = "# Generated by .codex/sync-agents.py;"
SKILL_MARKER = "<!-- Generated by .codex/sync-agents.py;"
NAME = re.compile(r"[a-z0-9]+(?:-[a-z0-9]+)*")


def metadata(source):
    text = source.read_text(encoding="utf-8")
    parts = text.split("---", 2)
    if len(parts) != 3 or parts[0].strip():
        raise ValueError(f"Missing YAML frontmatter: {source.relative_to(ROOT)}")
    fields = yaml.safe_load(parts[1])
    if not isinstance(fields, dict):
        raise ValueError(f"Invalid metadata: {source.relative_to(ROOT)}")
    name = fields.get("name")
    expected_name = source.parent.name if source.name == "SKILL.md" else source.stem
    if not isinstance(name, str) or not NAME.fullmatch(name) or name != expected_name:
        raise ValueError(f"Invalid or mismatched name: {source.relative_to(ROOT)}")
    if not isinstance(fields.get("description"), str) or not fields["description"].strip():
        raise ValueError(f"Missing description: {source.relative_to(ROOT)}")
    return fields


def expected_files():
    skill_sources = sorted((ROOT / ".claude" / "skills").glob("*/SKILL.md"))
    agent_sources = sorted((ROOT / ".claude" / "agents").glob("*.md"))
    if not skill_sources or not agent_sources:
        raise ValueError("Expected shared agents and skills under .claude/")
    skills = {source.parent.name: metadata(source) for source in skill_sources}
    output = {}
    for source in skill_sources:
        fields = skills[source.parent.name]
        name = fields["name"]
        # Only discovery metadata is copied. The body lives in one canonical source;
        # Windows junctions are not required for a fresh checkout (Accord docs review).
        frontmatter = yaml.safe_dump(
            {"name": name, "description": fields["description"]},
            allow_unicode=True,
            sort_keys=False,
            width=110,
        )
        output[ROOT / ".agents" / "skills" / name / "SKILL.md"] = (
            f"---\n{frontmatter}---\n\n"
            f"{SKILL_MARKER} edit .claude/skills/{name}/SKILL.md instead. -->\n\n"
            f"Read and follow [the shared {name} skill]"
            f"(../../../.claude/skills/{name}/SKILL.md) before doing this task.\n"
            "Resolve its relative links from that canonical source, not this discovery entry.\n"
            "Read AGENTS.md and preserve active session instructions and user authorization.\n"
        )

    for source in agent_sources:
        fields = metadata(source)
        declared = fields.get("skills", [])
        if not isinstance(declared, list) or any(
            not isinstance(skill, str) or skill not in skills for skill in declared
        ):
            raise ValueError(f"Invalid or missing project skills: {source.relative_to(ROOT)}")
        instructions = (
            "Read AGENTS.md, ARCHITECTURE.md and .claude/agents-roster.md from the repository root. "
            f"Then read {source.relative_to(ROOT).as_posix()} and follow its Markdown body "
            "as this role's instructions. Resolve its links relative to that source file. "
            "The product sources are docs/plano-desenvolvimento.md and docs/specs/README.md, "
            "plus the affected screen specifications. Distinguish planned, implemented and measured work. "
            "Its YAML model and tools fields configure Claude only; use this adapter's model "
            "and inherit session effort, permissions and available tools. Read SKILL.md files directly; "
            "do not assume Claude-only tools are installed. Delegation requires authorization "
            "under active session instructions. User authorization already given remains valid; "
            "do not request it again. Use Beads for tasks and durable knowledge, not private memory."
        )
        if declared:
            instructions += " Before starting, read these canonical project skills: " + ", ".join(
                f".claude/skills/{skill}/SKILL.md" for skill in declared
            ) + "."
        values = {
            "name": fields["name"],
            "description": fields["description"],
            # Preserve the existing runtime mapping; product documentation does not
            # authorize a model migration or permission change.
            "model": "gpt-6-astra" if fields.get("model") == "opus" else "gpt-6-sol",
            "developer_instructions": instructions,
        }
        output[ROOT / ".codex" / "agents" / f"{fields['name']}.toml"] = (
            f"{ADAPTER_MARKER} edit the shared Markdown source.\n"
            + "".join(f"{key} = {json.dumps(value, ensure_ascii=False)}\n" for key, value in values.items())
        )
    return output


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Report drift without writing files")
    args = parser.parse_args()
    expected = expected_files()
    problems = []
    # Preflight the entire batch before writing. A manual file or stale generated
    # role must be reviewed, rather than leaving a half-refreshed instruction set.
    for target in expected:
        if target.exists():
            existing = target.read_text(encoding="utf-8")
            marker = ADAPTER_MARKER if target.suffix == ".toml" else SKILL_MARKER
            if marker not in existing:
                problems.append(f"Refusing to overwrite manual file: {target.relative_to(ROOT)}")
    candidates = list((ROOT / ".codex" / "agents").glob("*.toml"))
    candidates += list((ROOT / ".agents" / "skills").glob("*/SKILL.md"))
    for target in sorted(candidates):
        content = target.read_text(encoding="utf-8")
        if target not in expected and (ADAPTER_MARKER in content or SKILL_MARKER in content):
            problems.append(f"Obsolete generated file; review removal: {target.relative_to(ROOT)}")
    if problems:
        raise ValueError("\n".join(problems))

    drift = [target for target, content in expected.items()
             if not target.exists() or target.read_text(encoding="utf-8") != content]
    if args.check:
        if drift:
            for target in drift:
                print(f"Out of date: {target.relative_to(ROOT)}")
            return 1
        print(f"OK: {len(expected)} generated agent/skill files match their shared sources")
        return 0

    for target in drift:
        target.parent.mkdir(parents=True, exist_ok=True)
        target.write_text(expected[target], encoding="utf-8")
    print(f"Refreshed {len(drift)} of {len(expected)} generated agent/skill files")
    return 0


if __name__ == "__main__":
    try:
        sys.exit(main())
    except (ValueError, OSError, yaml.YAMLError) as error:
        print(error, file=sys.stderr)
        sys.exit(1)
